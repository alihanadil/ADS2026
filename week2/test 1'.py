def calculate_score():

    right_program = correct[mission][0]
    right_temperature = correct[mission][1]
    right_spin = correct[mission][2]
    right_rinses = correct[mission][3]

    score = 0

    # ------------------------------------------------------
    # ПРОГРАММА — 40%
    # ------------------------------------------------------

    if program == right_program:
        score += 40

    # ------------------------------------------------------
    # ТЕМПЕРАТУРА — 25%
    # ------------------------------------------------------

    difference = abs(temperature - right_temperature)

    if difference == 0:
        score += 25
    elif difference <= 10:
        score += 21
    elif difference <= 20:
        score += 17
    elif difference <= 30:
        score += 12
    elif difference <= 40:
        score += 7

    # ------------------------------------------------------
    # ОТЖИМ — 20%
    # ------------------------------------------------------

    difference = abs(
        spin_values[spin_index] - right_spin
    )

    if difference == 0:
        score += 20
    elif difference <= 200:
        score += 17
    elif difference <= 400:
        score += 14
    elif difference <= 600:
        score += 9
    elif difference <= 800:
        score += 5

    # ------------------------------------------------------
    # ПОЛОСКАНИЯ — 15%
    # ------------------------------------------------------

    difference = abs(rinses - right_rinses)

    if difference == 0:
        score += 15
    elif difference == 1:
        score += 11
    elif difference == 2:
        score += 7
    elif difference == 3:
        score += 3

    return score


