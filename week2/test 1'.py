fonts = {}


def get_font(size):
    if size not in fonts:
        fonts[size] = pygame.font.Font(None, size)
    return fonts[size]


def draw_text(value, x, y, size):
    image = get_font(size).render(str(value), True, (20, 20, 20))
    screen.blit(image, (x, y))


def draw_button(x, y, width, height, title, color):
    pygame.draw.rect(
        screen,
        color,
        (x, y, width, height),
        border_radius=16
    )

    pygame.draw.rect(
        screen,
        (60, 60, 60),
        (x, y, width, height),
        3,
        border_radius=16
    )

    image = get_font(42).render(title, True, (20, 20, 20))
    rect = image.get_rect(
        center=(x + width // 2, y + height // 2)
    )

    screen.blit(image, rect)


